export function getDemoMembers(): ForumMember[] {
  return BASE.map((m) => {
    const adminSpecial = getSpecialRankForMember(m.id);
    return {
      ...m,
      specialRankId: adminSpecial !== undefined ? adminSpecial ?? undefined : m.specialRankId,
    };
  });
}

export function getDemoMember(id: string): ForumMember | undefined {
  return getDemoMembers().find((m) => m.id === id);
}
